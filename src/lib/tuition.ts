export function presentSubject(subject: Subject, lang: Lang): Subject {
  if (lang === "hi") return subject;
  const en = subjectEn[subject.slug];
  if (!en) return subject;
  return { ...subject, name: en.name, focus: en.focus, bands: en.bands };
}
