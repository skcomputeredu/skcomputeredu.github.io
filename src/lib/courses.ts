export function courseTitle(course: { slug: string; name: string; hindi: string }, lang: "en" | "hi") {
  if (englishFull[course.slug]) return course.name;
  return lang === "en" ? course.name : course.hindi;
}

export function courseFullForm(course: { slug: string; name: string }, lang: "en" | "hi") {
  const line = lang === "en" ? englishFull[course.slug] : hindiFull[course.slug];
  if (!line || line === course.name) return "";
  return line;
}

export function categoryLabel(id: CategoryId, lang: "en" | "hi") {
  return categories.find((category) => category.id === id)?.label[lang] ?? id;
}
